    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
         String email = JOptionPane.showInputDialog(this, "Enter Email:");
        if (email == null || email.trim().isEmpty()) return;
 
        String username = JOptionPane.showInputDialog(this, "Enter Username:");
        if (username == null || username.trim().isEmpty()) return;
 
        String password = JOptionPane.showInputDialog(this, "Enter Password:");
        if (password == null || password.trim().isEmpty()) return;
 
        try (Connection conn = DBConnection.getConnection()) {
            PreparedStatement ps = conn.prepareStatement(
                "INSERT INTO users (email, username, password) VALUES (?, ?, ?)");
            ps.setString(1, email.trim());
            ps.setString(2, username.trim());
            ps.setString(3, password.trim());
            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "User added successfully!");
            loadUsers();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error adding user: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a user to update.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
 
        int id             = (int)    jTable1.getValueAt(selectedRow, 0);
        String currentEmail    = (String) jTable1.getValueAt(selectedRow, 1);
        String currentUsername = (String) jTable1.getValueAt(selectedRow, 2);
        String currentPassword = (String) jTable1.getValueAt(selectedRow, 3);
 
        String newEmail = JOptionPane.showInputDialog(this, "Edit Email:", currentEmail);
        if (newEmail == null || newEmail.trim().isEmpty()) return;
 
        String newUsername = JOptionPane.showInputDialog(this, "Edit Username:", currentUsername);
        if (newUsername == null || newUsername.trim().isEmpty()) return;
 
        String newPassword = JOptionPane.showInputDialog(this, "Edit Password:", currentPassword);
        if (newPassword == null || newPassword.trim().isEmpty()) return;
 
        try (Connection conn = DBConnection.getConnection()) {
            PreparedStatement ps = conn.prepareStatement(
                "UPDATE users SET email=?, username=?, password=? WHERE id=?");
            ps.setString(1, newEmail.trim());
            ps.setString(2, newUsername.trim());
            ps.setString(3, newPassword.trim());
            ps.setInt(4, id);
            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "User updated successfully!");
            loadUsers();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error updating user: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a user to delete.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
 
        int id = (int) jTable1.getValueAt(selectedRow, 0);
        String username = (String) jTable1.getValueAt(selectedRow, 2);
 
        int confirm = JOptionPane.showConfirmDialog(this,
            "Are you sure you want to delete \"" + username + "\"?",
            "Delete User", JOptionPane.YES_NO_OPTION);
 
        if (confirm == JOptionPane.YES_OPTION) {
            try (Connection conn = DBConnection.getConnection()) {
                PreparedStatement ps = conn.prepareStatement("DELETE FROM users WHERE id=?");
                ps.setInt(1, id);
                ps.executeUpdate();
                JOptionPane.showMessageDialog(this, "User deleted successfully!");
                loadUsers();
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Error deleting user: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

